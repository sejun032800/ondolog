export function buildDescription(input: {
  core: EnneagramCore
  attachment: AttachmentType
  big5: Big5
  sternberg: { intimacy: number; passion: number; commitment: number }
}): string[] {
  const keys = Object.keys(BIG5_TEXT) as Array<keyof Big5>
  const hi = keys.reduce((a, b) => (input.big5[b] > input.big5[a] ? b : a))
  const lo = keys.reduce((a, b) => (input.big5[b] < input.big5[a] ? b : a))
  const s = input.sternberg
  const top = (Object.keys(s) as Array<keyof typeof s>).reduce((a, b) => (s[b] > s[a] ? b : a))
  return [
    CORE_TEXT[input.core],
    ATTACHMENT_TEXT[input.attachment],
    `빅5에서는 ${BIG5_TEXT[hi].label}이 가장 높게 나왔습니다. ${BIG5_TEXT[hi].high} 반대로 ${BIG5_TEXT[lo].label}은 낮은 편이라, ${BIG5_TEXT[lo].low} ${STERN_TEXT[top]}`,
  ]
}
